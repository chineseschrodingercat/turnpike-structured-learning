#!/usr/bin/env python3
r"""LaTeX tables of the 1D tests (log section 32, report E21) from runs/tc1d/summary.json (analyze_tc1d.py).
Writes runs/tc1d/e21_tab_{main,bins,seeds}.tex (table bodies, \input by report/sections/e21_tc1d.tex)."""

from __future__ import annotations

import json
import pathlib

import numpy as np

S = json.loads(pathlib.Path("runs/tc1d/summary.json").read_text())
ROWS = [("oracle_T1", "local oracle, $\\Ttr=1$"), ("oracle_T2", "local oracle, $\\Ttr=2$"), ("oracle_T4", "local oracle, $\\Ttr=4$"),
        ("tp_T1", "TurnpikeNet $r=4$"), ("tc_T1", "\\texttt{cnn\\_res\\_tc}, $W=127$, $L=0.1$"),
        ("tc_T2", "\\texttt{cnn\\_res\\_tc}, $W=255$, $L=0.2$"), ("tc_T4", "\\texttt{cnn\\_res\\_tc}, $W=511$, $L=0.4$"),
        ("hyb_T1", "hybrid, joint training"), ("hyb2_T1", "hybrid, two-stage")]


def pct(v, d=3):
    v = 100 * float(v)
    if v == 0:
        return "0"
    if v >= 10:
        return f"{v:.1f}"
    if v >= 1:
        return f"{v:.2f}"
    return f"{v:.{d}g}" if v < 0.01 else f"{v:.3f}"


def main_table():
    out = []
    for ex in ("e01", "e08"):
        out.append(f"\\midrule\\multicolumn{{8}}{{@{{}}l}}{{\\emph{{{'E01: linear, constant target' if ex == 'e01' else 'E08: semilinear $\\gamma y^3$, constant target'}}}}}\\\\")
        for key, lab in ROWS:
            r = S[ex].get(key)
            if r is None:
                continue
            Ttr = r["train_T"][0]
            win = "--" if r["window"] is None else f"{r['window']:.3f}"
            if key.startswith("oracle"):
                win = f"{Ttr / 2:.1f}"
            params = "--" if r["params"] == 0 else f"{r['params'] / 1000:.1f}k"
            atT = f"{pct(np.mean(r[f'T{Ttr}_median']))} / {pct(np.mean(r[f'T{Ttr}_max']))}" if not key.startswith("oracle") else "0 / 0"
            t8 = f"{pct(np.mean(r['T8_median']))} / {pct(np.mean(r['T8_max']))}"
            tr = "--" if key.startswith("oracle") else f"{np.mean(r['transfer_init']):.2f} / {np.mean(r['transfer_term']):.2f}"
            secs = "--" if key.startswith("oracle") else f"{np.mean(r['train_seconds']):.0f}"
            out.append(f"{lab} & {Ttr} & {win} & {params} & {atT} & {t8} & {tr} & {secs}\\\\")
    return "\n".join(out)


def bin_table():
    out = []
    for ex in ("e01", "e08"):
        bins = list(S[ex]["tp_T1"]["T8_median_by_lam"].keys())
        counts = [S[ex]["tp_T1"]["T8_median_by_lam"][b][0] for b in bins]
        hdr = " & ".join(f"$[{b.split('-')[0]},{b.split('-')[1] if b.split('-')[1] != '100' else '\\infty'})$ ({c})" for b, c in zip(bins, counts))
        rate = "$\\lambda_1(\\beta)$" if ex == "e01" else "$\\lamlin$"
        rule = "\\toprule" if ex == "e01" else "\\midrule"
        out.append(f"{rule}\\emph{{{ex.upper()}}}, bins of {rate} & {hdr} & worst sample: error ($\\lambda$)\\\\\\midrule")
        for key, lab in ROWS:
            r = S[ex].get(key)
            if r is None:
                continue
            vals = " & ".join(pct(r["T8_median_by_lam"][b][1]) for b in bins)
            out.append(f"{lab}{' ($\\Ttr=' + str(r['train_T'][0]) + '$)' if not key.startswith('oracle') else ''} & {vals} & {pct(r['T8_worst']['err'])} ({r['T8_worst']['lam']:.2f})\\\\")
    return "\n".join(out)


def seed_table():
    out = []
    for ex in ("e01", "e08"):
        out.append(f"\\midrule\\multicolumn{{11}}{{@{{}}l}}{{\\emph{{{ex.upper()}}}}}\\\\")
        for key, lab in ROWS:
            r = S[ex].get(key)
            if r is None or key.startswith("oracle"):
                continue
            med, mx = np.array(r["T8_median"]) * 100, np.array(r["T8_max"]) * 100
            f = lambda a: " & ".join(f"{v:.3f}" if v < 1 else f"{v:.2f}" for v in a)  # noqa: E731
            out.append(f"{lab} ($\\Ttr={r['train_T'][0]}$) & {f(med)} & {med.mean():.3f} & {med.std():.3f} & {f(mx)} & {mx.mean():.2f} & {mx.std():.2f}\\\\")
    return "\n".join(out)


for name, fn in (("main", main_table), ("bins", bin_table), ("seeds", seed_table)):
    txt = f"% generated by robin/tc1d_tables.py from runs/tc1d/summary.json\n{fn()}\n"
    pathlib.Path(f"runs/tc1d/e21_tab_{name}.tex").write_text(txt, encoding="utf-8")
    print(txt)
